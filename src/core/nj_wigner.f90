! Wigner symbols in Float64 ... a direct port of the binomial-based algorithms of CGcoefficient.jl ...
    ! All angular momenta & projections are given doubled (dj = 2j), as in CGcoefficient.jl ...
    ! Invalid arguments give zero ...
module nj_wigner
    use nj_kinds
    implicit none
    private

    public :: wigner_init_float, fCG, f6j, f9j, fbinomial

    real(dp), allocatable :: Binom(:,:)
    integer :: Binom_nmax = -1

contains

    ! Extends the binomial table so that binomials up to n are available ...
        ! mode "Jmax" with rank 3/6/9 as in CGcoefficient.jl ...
    subroutine wigner_init_float(n,Mode,Rank)
        integer, intent(in) :: n, Rank
        character(len=*), intent(in) :: Mode
        integer :: n_req
        n_req = n
        if (Mode == 'Jmax') then
            if (Rank == 3) n_req = 3*n + 1
            if (Rank == 6) n_req = 4*n + 1
            if (Rank == 9) n_req = 5*n + 1
        else if (Mode == '2bjmax') then
            if (Rank == 3) n_req = 2*n + 1
            if (Rank == 6) n_req = 3*n + 1
            if (Rank == 9) n_req = 4*n + 1
        end if
        ! CGcoefficient.jl initializes nmax = 67 at module load ...
        call extend_binomial(max(n_req,67))
    end subroutine wigner_init_float

    ! Binomials are generated by Pascal's rule in quadruple precision & rounded to Float64 ...
        ! this reproduces the exact BigInt -> Float64 conversion used by CGcoefficient.jl ...
    subroutine extend_binomial(n)
        integer, intent(in) :: n
        real(qp), allocatable :: Row(:), New(:)
        integer :: m, k
        if (n <= Binom_nmax) return
        if (allocated(Binom)) deallocate(Binom)
        allocate(Binom(0:n,0:n))
        Binom = 0.0_dp
        allocate(Row(0:n), New(0:n))
        Row = 0.0_qp
        Row(0) = 1.0_qp
        Binom(0,0) = 1.0_dp
        do m = 1, n
            New(0) = 1.0_qp
            do k = 1, m - 1
                New(k) = Row(k-1) + Row(k)
            end do
            New(m) = 1.0_qp
            do k = 0, m
                Binom(m,k) = real(New(k),dp)
            end do
            Row(0:m) = New(0:m)
        end do
        Binom_nmax = n
    end subroutine extend_binomial

    pure real(dp) function fbinomial(n,k)
        integer, intent(in) :: n, k
        if (n < 0 .or. n > Binom_nmax .or. k < 0 .or. k > n) then
            fbinomial = 0.0_dp
        else
            fbinomial = Binom(n,k)
        end if
    end function fbinomial

    pure real(dp) function ub(n,k)
        integer, intent(in) :: n, k
        ub = Binom(n,k)
    end function ub

    pure logical function check_jm(dj,dm)
        integer, intent(in) :: dj, dm
        check_jm = (modulo(dj + dm,2) == 0) .and. (abs(dm) <= dj)
    end function check_jm

    pure logical function check_couple(dj1,dj2,dj3)
        integer, intent(in) :: dj1, dj2, dj3
        check_couple = (dj1 >= 0) .and. (dj2 >= 0) .and. (modulo(dj1 + dj2 + dj3,2) == 0) .and. &
                       (abs(dj1 - dj2) <= dj3) .and. (dj3 <= dj1 + dj2)
    end function check_couple

    pure real(dp) function rphase(n)
        integer, intent(in) :: n
        rphase = merge(-1.0_dp, 1.0_dp, modulo(n,2) == 1)
    end function rphase

    ! Clebsch-Gordan coefficient <j1 m1 j2 m2 | j3 m3> ...
    pure real(dp) function fCG(dj1,dj2,dj3,dm1,dm2,dm3)
        integer, intent(in) :: dj1, dj2, dj3, dm1, dm2, dm3
        integer :: J, Jm1, Jm2, Jm3, j1mm1, j2mm2, j3mm3, j2pm2, Low, High, z
        real(dp) :: A, B
        fCG = 0.0_dp
        if (.not. (check_jm(dj1,dm1) .and. check_jm(dj2,dm2) .and. check_jm(dj3,dm3))) return
        if (.not. check_couple(dj1,dj2,dj3)) return
        if (dm1 + dm2 /= dm3) return
        J = (dj1 + dj2 + dj3) / 2
        Jm1 = J - dj1
        Jm2 = J - dj2
        Jm3 = J - dj3
        j1mm1 = (dj1 - dm1) / 2
        j2mm2 = (dj2 - dm2) / 2
        j3mm3 = (dj3 - dm3) / 2
        j2pm2 = (dj2 + dm2) / 2
        A = sqrt(ub(dj1,Jm2) * ub(dj2,Jm3) / ( &
            ub(J + 1,Jm3) * ub(dj1,j1mm1) * &
            ub(dj2,j2mm2) * ub(dj3,j3mm3)))
        B = 0.0_dp
        Low = max(0, j1mm1 - Jm2, j2pm2 - Jm1)
        High = min(Jm3, j1mm1, j2pm2)
        do z = Low, High
            B = -B + ub(Jm3,z) * ub(Jm2,j1mm1 - z) * ub(Jm1,j2pm2 - z)
        end do
        fCG = rphase(High) * A * B
    end function fCG

    ! Wigner 6j symbol {j1 j2 j3; j4 j5 j6} ...
    pure real(dp) function f6j(dj1,dj2,dj3,dj4,dj5,dj6)
        integer, intent(in) :: dj1, dj2, dj3, dj4, dj5, dj6
        integer :: j123, j156, j426, j453, jpm123, jpm132, jpm231, jpm156, jpm426, jpm453, Low, High, x
        real(dp) :: A, B
        f6j = 0.0_dp
        if (.not. (check_couple(dj1,dj2,dj3) .and. check_couple(dj1,dj5,dj6) .and. &
                   check_couple(dj4,dj2,dj6) .and. check_couple(dj4,dj5,dj3))) return
        j123 = (dj1 + dj2 + dj3) / 2
        j156 = (dj1 + dj5 + dj6) / 2
        j426 = (dj4 + dj2 + dj6) / 2
        j453 = (dj4 + dj5 + dj3) / 2
        jpm123 = (dj1 + dj2 - dj3) / 2
        jpm132 = (dj1 + dj3 - dj2) / 2
        jpm231 = (dj2 + dj3 - dj1) / 2
        jpm156 = (dj1 + dj5 - dj6) / 2
        jpm426 = (dj4 + dj2 - dj6) / 2
        jpm453 = (dj4 + dj5 - dj3) / 2
        A = sqrt(ub(j123 + 1,dj1 + 1) * ub(dj1,jpm123) / ( &
            ub(j156 + 1,dj1 + 1) * ub(dj1,jpm156) * &
            ub(j453 + 1,dj4 + 1) * ub(dj4,jpm453) * &
            ub(j426 + 1,dj4 + 1) * ub(dj4,jpm426)))
        B = 0.0_dp
        Low = max(j123, j453, j426, j156)
        High = min(jpm123 + j453, jpm132 + j426, jpm231 + j156)
        do x = Low, High
            B = -B + ub(x + 1,j123 + 1) * ub(jpm123,x - j453) * &
                     ub(jpm132,x - j426) * ub(jpm231,x - j156)
        end do
        f6j = rphase(High) * A * B / real(dj4 + 1,dp)
    end function f6j

    ! Wigner 9j symbol {j1 j2 j3; j4 j5 j6; j7 j8 j9} ...
    pure real(dp) function f9j(dj1,dj2,dj3,dj4,dj5,dj6,dj7,dj8,dj9)
        integer, intent(in) :: dj1, dj2, dj3, dj4, dj5, dj6, dj7, dj8, dj9
        integer :: j123, j456, j789, j147, j258, j369
        integer :: pm123, pm132, pm231, pm456, pm465, pm564, pm789, pm798, pm897
        integer :: dtl, dth, dt, j19t, j26t, j48t, xl, xh, yl, yh, zl, zh, x, y, z
        real(dp) :: P0_nu, P0_de, P0, PABC, Pt_de, At, Bt, Ct
        f9j = 0.0_dp
        if (.not. (check_couple(dj1,dj2,dj3) .and. check_couple(dj4,dj5,dj6) .and. check_couple(dj7,dj8,dj9))) return
        if (.not. (check_couple(dj1,dj4,dj7) .and. check_couple(dj2,dj5,dj8) .and. check_couple(dj3,dj6,dj9))) return
        j123 = (dj1 + dj2 + dj3) / 2
        j456 = (dj4 + dj5 + dj6) / 2
        j789 = (dj7 + dj8 + dj9) / 2
        j147 = (dj1 + dj4 + dj7) / 2
        j258 = (dj2 + dj5 + dj8) / 2
        j369 = (dj3 + dj6 + dj9) / 2
        pm123 = (dj1 + dj2 - dj3) / 2
        pm132 = (dj1 + dj3 - dj2) / 2
        pm231 = (dj2 + dj3 - dj1) / 2
        pm456 = (dj4 + dj5 - dj6) / 2
        pm465 = (dj4 + dj6 - dj5) / 2
        pm564 = (dj5 + dj6 - dj4) / 2
        pm789 = (dj7 + dj8 - dj9) / 2
        pm798 = (dj7 + dj9 - dj8) / 2
        pm897 = (dj8 + dj9 - dj7) / 2
        P0_nu = ub(j123 + 1,dj1 + 1) * ub(dj1,pm123) * &
                ub(j456 + 1,dj5 + 1) * ub(dj5,pm456) * &
                ub(j789 + 1,dj9 + 1) * ub(dj9,pm798)
        P0_de = ub(j147 + 1,dj1 + 1) * ub(dj1,(dj1 + dj4 - dj7)/2) * &
                ub(j258 + 1,dj5 + 1) * ub(dj5,(dj2 + dj5 - dj8)/2) * &
                ub(j369 + 1,dj9 + 1) * ub(dj9,(dj3 + dj9 - dj6)/2)
        P0 = P0_nu / P0_de
        dtl = max(abs(dj2 - dj6), abs(dj4 - dj8), abs(dj1 - dj9))
        dth = min(dj2 + dj6, dj4 + dj8, dj1 + dj9)
        PABC = 0.0_dp
        do dt = dtl, dth, 2
            j19t = (dj1 + dj9 + dt) / 2
            j26t = (dj2 + dj6 + dt) / 2
            j48t = (dj4 + dj8 + dt) / 2
            Pt_de = ub(j19t + 1,dt + 1) * ub(dt,(dj1 + dt - dj9)/2) * &
                    ub(j26t + 1,dt + 1) * ub(dt,(dj2 + dt - dj6)/2) * &
                    ub(j48t + 1,dt + 1) * ub(dt,(dj4 + dt - dj8)/2)
            Pt_de = Pt_de * real((dt + 1)**2,dp)
            xl = max(j123, j369, j26t, j19t)
            xh = min(pm123 + j369, pm132 + j26t, pm231 + j19t)
            At = 0.0_dp
            do x = xl, xh
                At = -At + ub(x + 1,j123 + 1) * ub(pm123,x - j369) * &
                           ub(pm132,x - j26t) * ub(pm231,x - j19t)
            end do
            yl = max(j456, j26t, j258, j48t)
            yh = min(pm456 + j26t, pm465 + j258, pm564 + j48t)
            Bt = 0.0_dp
            do y = yl, yh
                Bt = -Bt + ub(y + 1,j456 + 1) * ub(pm456,y - j26t) * &
                           ub(pm465,y - j258) * ub(pm564,y - j48t)
            end do
            zl = max(j789, j19t, j48t, j147)
            zh = min(pm789 + j19t, pm798 + j48t, pm897 + j147)
            Ct = 0.0_dp
            do z = zl, zh
                Ct = -Ct + ub(z + 1,j789 + 1) * ub(pm789,z - j19t) * &
                           ub(pm798,z - j48t) * ub(pm897,z - j147)
            end do
            PABC = PABC + (rphase(xh + yh + zh) * At * Bt * Ct) / Pt_de
        end do
        f9j = rphase(dth) * sqrt(P0) * PABC
    end function f9j

end module nj_wigner
